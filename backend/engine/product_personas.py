# ── Master Registry ───────────────────────────────────────────────────────────

ALL_PERSONAS: dict[str, PersonaDefinition] = {
    p.key: p for p in [
        CROWDSTRIKE_FALCON, CARBON_BLACK, MICROSOFT_DEFENDER, SENTINELONE, ELASTIC_EDR,
        SPLUNK_ES, QRADAR, PALO_ALTO_XSIAM, MICROSOFT_SENTINEL, ELASTIC_SIEM,
        OKTA, MICROSOFT_ENTRA,
        PALO_ALTO_NGFW, FORTINET,
    ]
}

PERSONAS_BY_CATEGORY: dict[str, list[PersonaDefinition]] = {}
for _p in ALL_PERSONAS.values():
    PERSONAS_BY_CATEGORY.setdefault(_p.category, []).append(_p)


# ── Default stack for each security tier ──────────────────────────────────────

DEFAULT_STACK: dict[str, str] = {
    "edr":      "crowdstrike_falcon",
    "siem":     "splunk_es",
    "idp":      "okta",
    "firewall": "palo_alto_ngfw",
}


def get_persona(key: str) -> PersonaDefinition | None:
    return ALL_PERSONAS.get(key)


def get_stack_for_environment(env_settings: dict) -> dict[str, PersonaDefinition]:
    """Return the full persona stack for an environment given its settings dict."""
    stack = {}
    for category, default_key in DEFAULT_STACK.items():
        chosen = env_settings.get(f"{category}_persona", default_key)
        stack[category] = ALL_PERSONAS.get(chosen) or ALL_PERSONAS[default_key]
    return stack


def personas_to_api_spec(stack: dict[str, PersonaDefinition]) -> dict:
    """Describe the simulated API endpoints for a given stack (for Joti auto-discovery)."""
    return {
        category: {
            "vendor": p.vendor,
            "product": p.product,
            "api_base": p.api_prefix,
            "auth_scheme": p.auth_scheme,
            "capabilities": p.capabilities,
        }
        for category, p in stack.items()
    }
