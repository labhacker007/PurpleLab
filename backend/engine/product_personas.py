"""Product persona registry — defines what each vendor stack looks like.

A persona drives:
  - which log schema generators are selected
  - which vendor API emulation router handles inbound SOAR calls
  - the exact field names and event formats in generated logs
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class PersonaDefinition:
    key: str                        # machine key, e.g. "crowdstrike_falcon"
    vendor: str                     # display vendor name
    product: str                    # display product name
    category: str                   # edr | siem | idp | firewall | network
    api_prefix: str                 # route prefix, e.g. "/api/vendor/crowdstrike"
    log_source_types: list[str]     # source_type values generated by this persona
    alert_format: str               # "crowdstrike" | "splunk" | "defender" etc.
    auth_scheme: str                # "oauth2" | "basic" | "api_key" | "bearer"
    capabilities: list[str]         # response actions this persona supports
    field_aliases: dict[str, str]   # canonical_field → vendor_field translation
    metadata: dict[str, Any] = field(default_factory=dict)


