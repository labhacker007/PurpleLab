# ── HTTP JSON-RPC transport (server-to-server / Joti) ─────────────────────────

@router.post("")
async def mcp_jsonrpc(
    request: Request,
    x_api_key: Optional[str] = Header(None, alias="X-API-Key"),
    authorization: Optional[str] = Header(None),
):
    """JSON-RPC 2.0 over HTTP — used by Joti, custom integrations, CLI.

    Supports single requests and batch arrays:
      {"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"...","arguments":{...}}}
      [{"jsonrpc":"2.0",...}, {"jsonrpc":"2.0",...}]
    """
    auth_key = _check_auth(x_api_key, authorization)

    try:
        body = await request.json()
    except Exception:
        return JSONResponse(
            status_code=400,
            content={"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": "Parse error"}},
        )

    if isinstance(body, list):
        responses = [await handle_request(item, auth_key) for item in body]
        return JSONResponse(content=responses)

    response = await handle_request(body, auth_key)
    status = 401 if response.get("error", {}).get("code") == -32001 else 200
    return JSONResponse(status_code=status, content=response)


# ── SSE transport (Claude Desktop / VS Code / Cursor) ─────────────────────────

@router.get("/sse")
async def mcp_sse_connect(
    request: Request,
    x_api_key: Optional[str] = Header(None, alias="X-API-Key"),
    authorization: Optional[str] = Header(None),
):
    """SSE connection endpoint — MCP clients open a persistent SSE stream here.

    The client then POSTs JSON-RPC messages to /api/v2/mcp/messages?session_id=<id>
    and receives responses on this stream.

    Compatible with: Claude Desktop, VS Code MCP extension, Cursor, mcp CLI.

    How to connect with Claude Code CLI:
      claude mcp add purplelab \\
        --transport sse \\
        --url http://localhost:8002/api/v2/mcp/sse \\
        --header "X-API-Key: purplelab-dev-key"
    """
    auth_key = _check_auth(x_api_key, authorization)
    if not auth_key:
        raise HTTPException(status_code=401, detail="Invalid or missing X-API-Key")

    session_id = str(uuid.uuid4())
    queue: asyncio.Queue = asyncio.Queue()
    _sse_sessions[session_id] = queue

    async def event_stream() -> AsyncGenerator[str, None]:
        # Send endpoint event so client knows where to POST messages
        messages_url = f"/api/v2/mcp/messages?session_id={session_id}"
        yield f"event: endpoint\ndata: {messages_url}\n\n"

        try:
            while True:
                if await request.is_disconnected():
                    break
                try:
                    msg = await asyncio.wait_for(queue.get(), timeout=15.0)
                    data = json.dumps(msg)
                    yield f"data: {data}\n\n"
                except asyncio.TimeoutError:
                    # Keepalive ping
                    yield ": keepalive\n\n"
        finally:
            _sse_sessions.pop(session_id, None)

    return StreamingResponse(
        event_stream(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
            "X-MCP-Session-ID": session_id,
        },
    )


@router.post("/messages")
async def mcp_sse_messages(
    request: Request,
    session_id: str,
    x_api_key: Optional[str] = Header(None, alias="X-API-Key"),
    authorization: Optional[str] = Header(None),
):
    """Receive JSON-RPC messages for an SSE session and route response back.

    The client POSTs here; responses are pushed to the SSE stream identified
    by session_id.
    """
    auth_key = _check_auth(x_api_key, authorization)
    if not auth_key:
        raise HTTPException(status_code=401, detail="Invalid or missing X-API-Key")

    queue = _sse_sessions.get(session_id)
    if not queue:
        raise HTTPException(status_code=404, detail=f"Session {session_id} not found or expired")

    try:
        body = await request.json()
    except Exception:
        raise HTTPException(status_code=400, detail="Invalid JSON body")

    if isinstance(body, list):
        for item in body:
            response = await handle_request(item, auth_key)
            await queue.put(response)
    else:
        response = await handle_request(body, auth_key)
        await queue.put(response)

    return JSONResponse(status_code=202, content={"accepted": True})
