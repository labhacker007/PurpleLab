"""MCP Server HTTP endpoint — PurpleLab as an industry-standard MCP server.

Supports three transports so any MCP client can connect:

  1. HTTP JSON-RPC (POST /api/v2/mcp)
     Used by: Joti MCP Hub, custom integrations, server-to-server calls.

  2. HTTP + SSE (GET /api/v2/mcp/sse  +  POST /api/v2/mcp/messages)
     Used by: Claude Desktop, VS Code MCP extension, Cursor, any SSE-capable client.

  3. Discovery (GET /api/v2/mcp)
     Returns tool catalogue + connection instructions without auth.

Authentication:
  Header: X-API-Key: <key>   (preferred)
  Header: Authorization: Bearer <key>

  Default dev key: purplelab-dev-key
  Production: set PURPLELAB_MCP_API_KEY env var (auto-generated by purplelab.sh)

Standard client configs are in mcp-clients.json at the project root.
"""
from __future__ import annotations

import asyncio
import json
import logging
import os
import uuid
from typing import Any, AsyncGenerator, Optional

from fastapi import APIRouter, Header, HTTPException, Request
from fastapi.responses import JSONResponse, StreamingResponse

from backend.mcp.server import handle_request, TOOLS

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/mcp", tags=["mcp"])

_API_KEY = os.getenv("PURPLELAB_MCP_API_KEY", "purplelab-dev-key")

# Per-session SSE message queues: session_id → asyncio.Queue
_sse_sessions: dict[str, asyncio.Queue] = {}


def _check_auth(x_api_key: Optional[str], authorization: Optional[str]) -> Optional[str]:
    """Return the API key if valid, else None."""
    key = x_api_key
    if not key and authorization:
        if authorization.startswith("Bearer "):
            key = authorization.removeprefix("Bearer ").strip()
    return key if key == _API_KEY else None


